TEST(SilkParameters, MatchesReference) {
    for (const ParamCase& test : kCases) {
        player::audio::silk::SilkParamState state;
        state.fs_khz = test.fs_khz;
        state.nb_subfr = test.nb_subfr;
        state.lpc_order = test.fs_khz == 16 ? 16 : 10;
        state.nlsf_codebook = test.fs_khz == 16
                                  ? &player::audio::silk::kNlsfCodebookWb
                                  : &player::audio::silk::kNlsfCodebookNbMb;
        state.first_frame_after_reset = test.first_after_reset;
        state.loss_count = test.loss_cnt;
        state.last_gain_index = static_cast<int8_t>(test.prev_gain_index);
        for (int i = 0; i < 16; ++i) state.prev_nlsf_q15[i] = test.prev_nlsf[i];
        player::audio::silk::SilkIndices indices;
        indices.signal_type = test.signal_type;
        indices.quant_offset_type = test.quant_offset;
        for (int i = 0; i < 4; ++i) indices.gains_indices[i] = test.gains[i];
        for (int i = 0; i < 17; ++i) indices.nlsf_indices[i] = test.nlsf[i];
        indices.nlsf_interp_coef_q2 = test.interp;
        indices.lag_index = test.lag_index;
        indices.contour_index = test.contour;
        indices.per_index = test.per_index;
        for (int i = 0; i < 4; ++i) indices.ltp_index[i] = test.ltp[i];
        indices.ltp_scale_index = test.ltp_scale;
        player::audio::silk::SilkDecoderControl control;
        player::audio::silk::decodeParameters(
            state, indices,
            static_cast<player::audio::silk::CondCoding>(test.cond), control);
        for (int i = 0; i < 4; ++i) {
            EXPECT_EQ(control.gains_q16[i], test.gain_out[i]) << "gain " << i;
        }
        for (int i = 0; i < 16; ++i) {
            EXPECT_EQ(control.pred_coef_q12[0][i], test.lpc0[i]) << "lpc0 " << i;
            EXPECT_EQ(control.pred_coef_q12[1][i], test.lpc1[i]) << "lpc1 " << i;
        }
        for (int i = 0; i < 20; ++i) {
            EXPECT_EQ(control.ltp_coef_q14[i], test.ltp_out[i]) << "ltp " << i;
        }
        for (int i = 0; i < 4; ++i) {
            EXPECT_EQ(control.pitch_l[i], test.pitch_l[i]) << "pitch " << i;
        }
        EXPECT_EQ(control.ltp_scale_q14, test.ltp_scale_out);
        EXPECT_EQ(state.last_gain_index, test.gain_index_out);
        for (int i = 0; i < 16; ++i) {
            EXPECT_EQ(state.prev_nlsf_q15[i], test.nlsf_out[i]) << "nlsf " << i;
        }
    }
}
