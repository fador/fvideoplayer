TEST(SilkIndices, MatchesReference) {
    for (const IndicesCase& test : kCases) {
        player::audio::silk::SilkState state;
        state.fs_khz = test.fs_khz;
        state.nb_subfr = test.nb_subfr;
        state.nlsf_codebook = test.fs_khz == 16
                                  ? &player::audio::silk::kNlsfCodebookWb
                                  : &player::audio::silk::kNlsfCodebookNbMb;
        state.pitch_lag_low_bits_icdf = test.fs_khz == 16
                                            ? player::audio::silk::kSilkUniform8Icdf
                                            : (test.fs_khz == 12
                                                   ? player::audio::silk::kSilkUniform6Icdf
                                                   : player::audio::silk::kSilkUniform4Icdf);
        if (test.fs_khz == 8) {
            state.pitch_contour_icdf = test.nb_subfr == 4
                                           ? player::audio::silk::kSilkPitchContourNbIcdf
                                           : player::audio::silk::kSilkPitchContour10msNbIcdf;
        } else {
            state.pitch_contour_icdf = test.nb_subfr == 4
                                           ? player::audio::silk::kSilkPitchContourIcdf
                                           : player::audio::silk::kSilkPitchContour10msIcdf;
        }
        state.ec_prev_signal_type = test.prev_type;
        state.ec_prev_lag_index = test.prev_lag;
        uint8_t vad[3] = {static_cast<uint8_t>(test.vad), 0, 0};
        state.vad_flags = vad;
        player::audio::opus::RangeDecoder decoder(test.packet, 64);
        player::audio::silk::SilkIndices indices;
        player::audio::silk::decodeIndices(
            state, decoder, 0,
            test.lbrr ? player::audio::silk::DecodeLbrr::Yes
                      : player::audio::silk::DecodeLbrr::No,
            static_cast<player::audio::silk::CondCoding>(test.cond), indices);
        EXPECT_EQ(indices.signal_type, test.signal_type);
        EXPECT_EQ(indices.quant_offset_type, test.quant_offset);
        for (int i = 0; i < 4; ++i) {
            EXPECT_EQ(indices.gains_indices[i], test.gains[i]) << "gain " << i;
        }
        for (int i = 0; i < 17; ++i) {
            EXPECT_EQ(indices.nlsf_indices[i], test.nlsf[i]) << "nlsf " << i;
        }
        EXPECT_EQ(indices.nlsf_interp_coef_q2, test.interp);
        EXPECT_EQ(indices.lag_index, test.lag);
        EXPECT_EQ(indices.contour_index, test.contour);
        EXPECT_EQ(indices.per_index, test.per_index);
        for (int i = 0; i < 4; ++i) {
            EXPECT_EQ(indices.ltp_index[i], test.ltp[i]) << "ltp " << i;
        }
        EXPECT_EQ(indices.ltp_scale_index, test.ltp_scale);
        EXPECT_EQ(indices.seed, test.seed);
        EXPECT_EQ(state.ec_prev_lag_index, test.prev_lag_out);
        EXPECT_EQ(state.ec_prev_signal_type, test.prev_type_out);
    }
}
